#!/usr/bin/env python3
"""Authenticate to a confirmed team instance with the reconstructed key."""

import argparse
import re
import socket
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey


DEFAULT_SEED = Path(__file__).resolve().parent / "extracted" / "seed.bin"


def crc16_modbus(data: bytes) -> int:
    crc = 0xFFFF
    for byte in data:
        crc ^= byte
        for _ in range(8):
            crc = (crc >> 1) ^ 0xA001 if crc & 1 else crc >> 1
    return crc


def exchange(stream, pdu: bytes) -> bytes:
    frame = pdu + crc16_modbus(pdu).to_bytes(2, "little")
    stream.write(b"XFER " + frame.hex().encode() + b"\n")
    stream.flush()

    line = stream.readline()
    if not line:
        raise EOFError("service closed the connection")
    response = bytes.fromhex(line.strip().decode())
    if len(response) < 4 or crc16_modbus(response[:-2]) != int.from_bytes(
        response[-2:], "little"
    ):
        raise ValueError("invalid RTU response or CRC")
    if response[0] != 0x17:
        raise ValueError("unexpected RTU unit")
    return response[:-2]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("host", help="team-confirmed challenge host")
    parser.add_argument("port", type=int, help="team-confirmed challenge port")
    parser.add_argument("--seed", type=Path, default=DEFAULT_SEED,
                        help="local seed generated by reconstruct.py")
    args = parser.parse_args()

    key = Ed25519PrivateKey.from_private_bytes(args.seed.read_bytes())
    with socket.create_connection((args.host, args.port), timeout=10) as sock:
        sock.settimeout(10)
        stream = sock.makefile("rwb", buffering=0)
        print(stream.readline().decode(errors="replace").strip())

        challenge = exchange(stream, bytes.fromhex("174153390002"))
        if challenge[:3] != b"\x17\x41\x20" or len(challenge) != 35:
            raise ValueError("unexpected maintenance challenge")

        signature = key.sign(b"SOLSTICE9/maintenance/v1" + challenge[3:])
        receipt = exchange(stream, b"\x17\x42" + signature)
        if receipt[:2] != b"\x17\x42" or len(receipt) < 3:
            raise ValueError("unexpected maintenance receipt")
        length = receipt[2]
        flag = receipt[3:3 + length].decode()
        if not re.fullmatch(r"DCTF\{[^{}]+\}", flag):
            raise ValueError("receipt does not match the expected flag format")
        print(flag)


if __name__ == "__main__":
    main()
